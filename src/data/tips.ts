export function getTipsForBreed(breed: string): BreedTipData {
  // Direct match
  if (BREED_TIPS[breed]) return BREED_TIPS[breed];

  // Partial match
  const key = Object.keys(BREED_TIPS).find(k =>
    breed.toLowerCase().includes(k.toLowerCase()) ||
    k.toLowerCase().includes(breed.toLowerCase())
  );
  if (key) return BREED_TIPS[key];

  return DEFAULT_TIP;
}
