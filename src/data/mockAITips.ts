export function getDailyTip(size: string, ageYears: number): string {
  const season = getSeason();
  const group  = getSizeGroup(size);
  const pool   = TIPS[group][season];

  // Deterministic daily rotation — changes each day
  const dayOfYear = Math.floor(
    (Date.now() - new Date(new Date().getFullYear(), 0, 0).getTime()) / 86_400_000
  );

  // Age modifier: prefer last items for seniors
  const offset = ageYears >= 7 ? pool.length - 1 : 0;
  return pool[(dayOfYear + offset) % pool.length];
}

export function getTipCycled(size: string, ageYears: number, offset: number): string {
  const season = getSeason();
  const group  = getSizeGroup(size);
  const pool   = TIPS[group][season];
  return pool[offset % pool.length];
}

export function getTipPoolSize(size: string): number {
  return TIPS[getSizeGroup(size)][getSeason()].length;
}
